using System.Globalization;
using System.Text;

namespace Nibras.BuildingBlocks.Testing.Isolation;

/// <summary>
/// Emits the committed test class of one service in <c>tests/TenantIsolation.Tests/Generated/</c>: its surfaces, one
/// test per surface and the pool swap (document 16 part 3.1). The class is regenerated and diffed on every build, so a
/// new endpoint or consumer without a test fails the build instead of going unattacked.
/// </summary>
public static class IsolationGenerator
{
    public const string Namespace = "Nibras.TenantIsolation.Tests.Generated";

    public static string ClassName(string service) => service + "Isolation";

    public static string FileName(string service) => ClassName(service) + ".g.cs";

    /// <param name="service">The Appendix L service name.</param>
    /// <param name="targetType">The target's type as the generated code names it, for example <c>Targets.Attendance</c>.</param>
    /// <param name="surfaces">The names of the service's surfaces, as <see cref="IsolationSurfaces"/> lists them.</param>
    public static string Emit(string service, string targetType, IReadOnlyList<string> surfaces)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(service);
        ArgumentException.ThrowIfNullOrWhiteSpace(targetType);
        ArgumentNullException.ThrowIfNull(surfaces);
        var fixture = $"IsolationFixture<{targetType}>";
        var code = new StringBuilder();
        code.Append(CultureInfo.InvariantCulture, $$"""
            // <auto-generated>
            //   Generated by IsolationGenerator from the endpoints and consumers of the {{service}} service (document 12 part 4.4).
            //   Do not edit: regenerate with tools/isolation/regenerate.ps1 or regenerate.sh, review the diff and commit it.
            // </auto-generated>
            using Xunit;

            namespace {{Namespace}};

            [Trait("Service", "{{service}}")]
            [Trait("TestCase", "TC-SEC-955")]
            public sealed class {{ClassName(service)}}({{fixture}} suite) : IClassFixture<{{fixture}}>
            {
                public static readonly string[] Surfaces =
                [

            """);
        foreach (var surface in surfaces)
        {
            code.Append(CultureInfo.InvariantCulture, $"        {Literal(surface)},\n");
        }

        code.Append("    ];\n");
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var surface in surfaces)
        {
            var consumer = surface.StartsWith(IsolationSurface.ConsumerPrefix, StringComparison.Ordinal);
            code.Append("\n    [Fact]\n");
            if (consumer)
            {
                code.Append("    [Trait(\"TestCase\", \"TC-DATA-645\")]\n");
            }

            code.Append(CultureInfo.InvariantCulture, $"    public Task {Unique(MethodName(surface), names)}() => suite.AttackAsync({Literal(surface)});\n");
        }

        code.Append(CultureInfo.InvariantCulture, $$"""

                [Fact]
                public Task {{Unique("PooledConnection_AfterTenantA_ServesTenantBNothingOfTenantA", names)}}() => suite.PoolSwapAsync();
            }

            """);
        return code.ToString();
    }

    /// <summary>
    /// <c>GET /api/v1/attendance/sessions/{id:guid}</c> becomes <c>GetSessionsById_AsTenantA_LeaksNothingOfTenantB</c>;
    /// <c>consumer attendance.session.closed.v1</c> becomes <c>ConsumeAttendanceSessionClosedV1_EnvelopeOfTenantB_WritesNothingToTenantA</c>.
    /// </summary>
    public static string MethodName(string surface)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(surface);
        if (surface.StartsWith(IsolationSurface.ConsumerPrefix, StringComparison.Ordinal))
        {
            var key = surface[IsolationSurface.ConsumerPrefix.Length..];
            return "Consume" + string.Concat(key.Split('.', '-', '_').Select(Pascal)) + "_EnvelopeOfTenantB_WritesNothingToTenantA";
        }

        var space = surface.IndexOf(' ', StringComparison.Ordinal);
        var name = new StringBuilder(Pascal(surface[..space].ToLowerInvariant()));
        // Skip /api/v{n}/{service}: every method of the class shares them.
        foreach (var segment in surface[(space + 1)..].Split('/', StringSplitOptions.RemoveEmptyEntries).Skip(3))
        {
            if (segment.StartsWith('{'))
            {
                var parameter = segment.Trim('{', '}').Split(':', '=', '?')[0].TrimStart('*');
                name.Append("By").Append(Pascal(parameter));
            }
            else
            {
                name.Append(string.Concat(segment.Split('-', '.').Select(Pascal)));
            }
        }

        return name.Append("_AsTenantA_LeaksNothingOfTenantB").ToString();
    }

    private static string Pascal(string word) =>
        word.Length == 0 ? word : char.ToUpper(word[0], CultureInfo.InvariantCulture) + word[1..];

    private static string Unique(string name, HashSet<string> taken)
    {
        var candidate = name;
        for (var i = 2; !taken.Add(candidate); i++)
        {
            candidate = string.Create(CultureInfo.InvariantCulture, $"{name}_{i}");
        }

        return candidate;
    }

    private static string Literal(string text) =>
        "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}
