// Generate docs/plan/16-annex-test-case-registry.md: every test-case identifier,
// the one document that defines it, what it proves, and who cites it (ADR-0020).
// It runs the same ownership code as kit-lint rule R20, so the registry and the
// rule cannot disagree.
//   node tools/plan-build/gen-tc-registry.mjs
import { readFileSync } from 'node:fs';
import { writeGenerated } from './write-generated.cjs';

import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildContext, testCaseOwnership } from '../kit-lint/kit-lint.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const OUT = 'docs/plan/16-annex-test-case-registry.md';
const ctx = buildContext(root);
const own = testCaseOwnership(ctx);

const short = (rel) => {
  let m = /appendix-([a-x])-/.exec(rel);
  if (m) return 'Appendix ' + m[1].toUpperCase();
  m = /06-services\/([a-z-]+)\.md$/.exec(rel);
  if (m) return m[1].split('-').map((w) => (w === 'bff' ? 'Bff' : w.charAt(0).toUpperCase() + w.slice(1))).join('.') + ' sheet';
  m = /docs\/plan\/(\d\d)-/.exec(rel);
  if (m) return 'document ' + m[1];
  m = /docs\/brief\/0(\d)-/.exec(rel);
  if (m) return ['', 'master brief', '', 'reference architecture'][Number(m[1])] || rel;
  return rel.replace(/^docs\//, '');
};
const clean = (t) => t.replace(/\|/g, '/').replace(/`/g, '').replace(/\s+/g, ' ').trim();
const cut = (t, n) => (t.length > n ? t.slice(0, n - 1).trimEnd() + '…' : t);

const reqText = new Map();
for (const l of readFileSync(join(root, 'docs/plan/03-requirements-catalog.md'), 'utf8').split(/\r?\n/)) {
  const m = /^\| (REQ-[A-Z0-9]+-\d{3}) \| ([^|]+)\|/.exec(l);
  if (m) reqText.set(m[1], m[2].trim());
}

const ids = new Set([...own.defs.keys(), ...own.cites.keys()]);
const rows = [];
const derived = [];
const problems = [];
for (const id of [...ids].sort((a, b) => a.localeCompare(b, 'en'))) {
  const citedBy = [...new Set((own.cites.get(id) || []).map((c) => short(c.file)))].filter((s) => s !== 'document 16-annex');
  const req = own.derivedReq(id);
  if (req) { derived.push({ id, req, citedBy }); continue; }
  const defs = own.defs.get(id);
  if (!defs) { problems.push(id + ' has no definition'); continue; }
  const files = [...new Set(defs.map((d) => d.file))];
  if (files.length > 1) problems.push(id + ' is defined in ' + files.join(', '));
  const d = defs[0];
  rows.push('| ' + id + ' | ' + short(d.file) + ', line ' + d.line + ' | ' + cut(clean(d.text), 150) + ' | ' + (citedBy.join(', ') || 'none') + ' |');
}

const areas = {};
for (const r of rows) { const a = r.split('-')[1]; areas[a] = (areas[a] || 0) + 1; }
const L = [];
const p = (x = '') => L.push(x);
p('# 16 (annex). Test-Case Registry');
p();
p('## Purpose');
p();
p('Every test-case identifier in the kit, the **one** document that defines it, what it proves, and every document that cites it. ADR-0020 sets the rule: a test is defined once and cited everywhere else. This annex is generated by `node tools/plan-build/gen-tc-registry.mjs` from the same code as kit-lint rule R20, which fails the lint on a second definition or a citation with none; editing it by hand is a defect. Document 16 owns the test strategy; this annex owns nothing but the list.');
p();
p('## Scope');
p();
p('| In scope | Owned elsewhere |');
p('|---|---|');
p('| Every `TC-` identifier in `docs/brief` and `docs/plan`, its owner, its meaning and its citations | The test itself: its owner document |');
p('| The derived acceptance tests of document 20 Section 2 | The requirement that each one proves: document 03 |');
p();
p('## Content');
p();
p('### 1. Summary');
p();
p('| Measure | Value |');
p('|---|---|');
p('| Test cases defined in one document | ' + rows.length + ' |');
p('| Derived acceptance tests (950 to 999), owned by their requirement | ' + derived.length + ' |');
p('| Identifiers defined in two documents or cited with no definition | ' + problems.length + ' |');
p('| Areas | ' + Object.keys(areas).length + ' |');
p();
p('### 2. How ownership is decided');
p();
p('| Rule | Detail |');
p('|---|---|');
p('| Defined | A table cell holds the identifier and nothing else, in the first column or in a column headed Test, Test case, TC, Identifier, Test case ID or Test id (Appendix W\'s Demo column included) |');
p('| Cited | Any other appearance. A cell such as "TC-ATT-003 (Appendix R)" is a citation by design |');
p('| Precedence when two documents want one test | Appendix R, then Appendix W, then the service sheet of the identifier\'s area, then the area\'s cross-cutting plan document, then any other document |');
p('| Same identifier, different tests | The lower-precedence document renumbers |');
p('| Derived acceptance test | `TC-<AREA>-(950 + requirement number)`, owned by the requirement (document 20 Section 2) |');
p();
p('### 3. The registry');
p();
p('| Test case | Defined in | What it proves | Cited by |');
p('|---|---|---|---|');
for (const r of rows) p(r);
p();
p('### 4. Derived acceptance tests');
p();
p('Each is specified by its requirement\'s Given, When, Then line in document 03, and written with this identifier by the slice that builds the requirement.');
p();
p('| Test case | Requirement | Cited by |');
p('|---|---|---|');
for (const d of derived) p('| ' + d.id + ' | ' + d.req + (reqText.has(d.req) ? ': ' + cut(clean(reqText.get(d.req)), 110) : ', which does not exist') + ' | ' + (d.citedBy.join(', ') || 'none') + ' |');
p();
p('## Decisions in force');
p();
p('| Decision | Record |');
p('|---|---|');
p('| `TC-<AREA>-<NNN>` is the unit of proof | ADR-0014 |');
p('| One definition per test case, citations name the owner, precedence as above | ADR-0020 |');
p('| This annex is generated, never edited by hand | ADR-0020 |');
p();
p('## Dependencies on other documents');
p();
p('| Document | What this one takes |');
p('|---|---|');
p('| Every document in `docs/brief` and `docs/plan` | The definitions and citations |');
p('| `03-requirements-catalog.md` | The requirement behind each derived acceptance test |');
p('| `16-test-strategy.md` | The strategy this annex serves |');
p();
p('## Open points');
p();
p('| Point | Default | Owner |');
p('|---|---|---|');
p('| ' + (problems.length ? problems.length + ' identifiers still fail the rule when this annex was generated' : 'None: every identifier has exactly one definition') + ' | Kit-lint R20 names each one | Architect |');
p();
p('## Review record');
p();
p('| Date | Reviewer | Result |');
p('|---|---|---|');
p('| ' + new Date().toISOString().slice(0, 10) + ' | Generated | ' + rows.length + ' test cases and ' + derived.length + ' derived acceptance tests |');
p();
p('## How this document is verified');
p();
p('| Claim | Proof |');
p('|---|---|');
p('| Every identifier has one definition | Kit-lint rule R20, which runs the same ownership code as this generator |');
p('| The annex is current | Kit-lint rule R23 reruns `gen-tc-registry.mjs --check` and fails when a test was added, renumbered or moved since the annex was generated |');
p();
writeGenerated(join(root, OUT), L.join('\n'));
console.log('registry: ' + rows.length + ' defined, ' + derived.length + ' derived, ' + problems.length + ' problems');
for (const x of problems.slice(0, 20)) console.log('  ' + x);
